import AppKit

/// Polls `NSPasteboard.changeCount` (the same mechanism Paste relies on — the
/// binary references `changeCount` and the nspasteboard.org marker types).
@MainActor
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int?

    var onNewItem: ((ClipItem) -> Void)?

    /// Password managers mark secrets with these types (see nspasteboard.org).
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private static let maxImageBytes = 15 * 1024 * 1024

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call after writing to the pasteboard ourselves, so we don't record our own write.
    func ignore(changeCount: Int) {
        ignoredChangeCount = changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if count == ignoredChangeCount {
            ignoredChangeCount = nil
            return
        }
        if let item = readItem() {
            onNewItem?(item)
        }
    }

    private func readItem() -> ClipItem? {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes) else { return nil }

        let source = NSWorkspace.shared.frontmostApplication

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipItem(kind: .file, fileURLs: urls, source: source)
        }

        if types.contains(.png) || types.contains(.tiff),
           let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           data.count <= Self.maxImageBytes {
            return ClipItem(kind: .image, imageData: data, source: source)
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipItem.fromString(string, source: source)
        }

        return nil
    }
}
